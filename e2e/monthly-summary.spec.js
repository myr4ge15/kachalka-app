import { test, expect } from '@playwright/test'
import { enterPin, tabbar, openTab } from './helpers.js'
test.use({ viewport: { width: 393, height: 793 } })

test('одноразовые итоги ведут в календарь месяца и не возвращаются после перезагрузки', async ({ page, context }) => {
  await context.addInitScript(() => {
    Object.defineProperty(window.navigator, 'onLine', { get: () => false, configurable: true })
  })
  await context.route(/supabase\.co/, (route) => route.abort())
  await page.goto('/kachalka-app/')
  const user = await page.evaluate(async () => (await import('/kachalka-app/src/test/e2eSeed.js')).seedE2E({ monthlyAutoShow: true }))
  await page.reload()
  await page.getByRole('button', { name: user.name }).click()
  await enterPin(page, user.pin)
  await expect(tabbar(page)).toBeVisible()
  await expect(page.getByRole('button', { name: /Твой месяц в цифрах/ })).toHaveCount(0)
  await page.evaluate(async (userId) => {
    const [{ saveWorkout }, { E2E_EXERCISES }] = await Promise.all([
      import('/kachalka-app/src/db/repo.js'), import('/kachalka-app/src/test/e2eSeed.js'),
    ])
    const now = new Date()
    for (const day of [1, 2, 3, 4, 5, 6, 7, 8, 9]) {
      await saveWorkout({ user_id: userId, performed_at: new Date(now.getFullYear(), now.getMonth() - 1, day, 12).toISOString(), entries: [{ exercise: { ...E2E_EXERCISES[0], name: 'Разведение ног в тренажере (Hip Abductor)' }, sets: [{ weight: 50 + day, reps: 5 }] }] })
    }
    await saveWorkout({ user_id: userId, performed_at: new Date(now.getFullYear(), now.getMonth(), 1, 12).toISOString(), entries: [{ exercise: E2E_EXERCISES[0], sets: [{ weight: 60, reps: 5 }] }] })
  }, user.id)
  const summary = page.getByRole('dialog', { name: 'Итоги месяца' })
  await expect(summary.getByText('Рабочие подходы')).toBeVisible()
  await expect(summary.getByRole('heading', { level: 2 })).toHaveText('9тренировок')
  await page.evaluate(() => document.fonts.ready)
  await expect(summary.locator('.monthly-hero')).toHaveCSS('font-family', /Sofia Sans Condensed/)
  await expect(summary.locator('.monthly-hero span')).toHaveCSS('font-family', /Onest/)
  await expect(summary.locator('.monthly-stats dd').first()).toHaveCSS('font-family', /Sofia Sans Condensed/)
  await expect(summary.locator('.monthly-fireworks')).toHaveCSS('pointer-events', 'none')
  await expect(summary.locator('.monthly-fireworks')).toBeHidden()
  const panel = await summary.boundingBox()
  const viewport = page.viewportSize()
  expect(Math.abs(panel.x + panel.width / 2 - viewport.width / 2)).toBeLessThan(2)
  expect(Math.abs(panel.y + panel.height / 2 - viewport.height / 2)).toBeLessThan(2)
  const done = await summary.getByRole('button', { name: 'Готово', exact: true }).boundingBox()
  expect(panel.y + panel.height - done.y - done.height).toBeLessThanOrEqual(24)
  expect(await summary.locator('.sheet-scroll').evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.setViewportSize({ width: 320, height: 568 })
  await expect(summary.getByRole('button', { name: 'Готово', exact: true })).toBeInViewport()
  expect(await summary.locator('.sheet-scroll').evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.setViewportSize({ width: 393, height: 793 })
  await page.screenshot({ path: 'test-results/monthly-summary.png', fullPage: true })
  await summary.getByRole('button', { name: 'Тренировки за месяц' }).click()
  const calendar = page.getByRole('dialog', { name: 'Календарь' })
  await expect(calendar).toBeVisible()
  await expect(calendar.getByText('9 тренировок', { exact: true })).toBeVisible()
  await expect(calendar.getByText('Нет тренировок в этот день.')).toHaveCount(0)
  await calendar.getByRole('button', { name: 'закрыть', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Мои тренировки' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Сбросить/ })).toBeVisible()
  for (const width of [393, 1866]) {
    await page.setViewportSize({ width, height: 850 })
    await expect(page.getByRole('button', { name: /Сбросить/ })).toBeVisible()
    await expect(page.locator('.tag-filter')).toBeVisible()
    const month = await page.getByRole('button', { name: /Сбросить/ }).boundingBox()
    const groups = await page.locator('.tag-filter').boundingBox()
    expect(groups.y - month.y - month.height).toBeGreaterThanOrEqual(8)
  }
  await page.screenshot({ path: 'test-results/history-month-filter.png', fullPage: true })
  await page.setViewportSize({ width: 393, height: 793 })
  await openTab(page, 'Главная')
  await expect(page.getByRole('button', { name: /Твой месяц в цифрах/ })).toHaveCount(0)
  await page.reload()
  await expect(tabbar(page)).toBeVisible()
  await expect(page.getByRole('button', { name: /Твой месяц в цифрах/ })).toHaveCount(0)
  await openTab(page, 'Прогресс')
  await expect(page.getByText('Итоги месяца', { exact: true })).toHaveCount(0)
  const nextMonth = new Date()
  nextMonth.setMonth(nextMonth.getMonth() + 1, 2)
  await page.clock.setFixedTime(nextMonth)
  await openTab(page, 'Главная')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(page.getByRole('dialog', { name: 'Итоги месяца' })).toBeVisible()
  await expect(page.getByRole('dialog', { name: 'Итоги месяца' }).locator('.monthly-fireworks')).toBeHidden()
  await page.getByRole('button', { name: 'Готово', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Итоги месяца' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Твой месяц в цифрах/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Открыть профиль' }).click()
  await page.getByRole('button', { name: /Итоги месяца/ }).click()
  const archive = page.getByRole('dialog', { name: 'Итоги месяца' })
  await archive.getByRole('button', { name: 'Выбрать месяц' }).click()
  await expect(archive.getByRole('button', { name: 'Выбрать месяц' }).locator('svg.ui-chevron--toggle.is-open')).toHaveCount(1)
  await archive.getByRole('group', { name: 'Месяц итогов' }).getByRole('button').nth(1).click()
  await archive.getByRole('button', { name: 'Выбрать месяц' }).click()
  await archive.getByRole('group', { name: 'Месяц итогов' }).getByRole('button').first().click()
  await archive.getByRole('button', { name: 'Выбрать месяц' }).click()
  await archive.getByRole('group', { name: 'Месяц итогов' }).getByRole('button').nth(1).click()
  await expect(archive.getByRole('heading', { level: 2 })).toHaveText('9тренировок')
  await expect(archive.locator('.monthly-fireworks')).toHaveCount(0)
  await archive.getByRole('button', { name: 'Тренировки за месяц' }).click()
  await expect(page.getByRole('dialog', { name: 'Календарь' }).getByText('9 тренировок', { exact: true })).toBeVisible()
})
