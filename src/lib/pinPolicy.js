// Слабые PIN. С П4 «Моего круга» (07.10.2026, решение владельца) — только ~10 самых
// частых: лесенки и прочие правила ревью 06.10 убраны (раздражали, а перебор и так
// держат лимиты входа на сервере). Уже заданные PIN не трогаем.
// Паритет с сервером: supabase/functions/_shared/pin.ts (isWeakPin) — тот же список
// в pinPolicy.test.js и _shared/pin_test.ts. Сервер проверяет сам: клиентская
// проверка — только чтобы сказать сразу, без похода в сеть.
export const WEAK_PINS = ['1234', '0000', '1111', '1212', '7777', '2000', '4444', '2222', '6969', '9999']
const WEAK = new Set(WEAK_PINS)

export const WEAK_PIN_TEXT = 'Слишком простой PIN (1234, 0000…) — придумай другой.'

export function isWeakPin(pin) {
  return WEAK.has(String(pin ?? ''))
}
