// Слабые PIN (ревью 06.10.2026, п. 2). Лимит попыток стоит на учетку, а подбирать
// можно «по кругу»: один популярный PIN на каждом участнике. Самые частые 4-значные
// PIN (одинаковые цифры, лесенки, 1212/1122/2000/1004/6969/2580…) покрывают заметную
// долю реальных — новые PIN из них не принимаем. Уже заданные PIN не трогаем.
// Паритет с сервером: supabase/functions/_shared/pin.ts (isWeakPin) — тот же список
// примеров в pinPolicy.test.js и _shared/pin_test.ts. Сервер проверяет сам: клиентская
// проверка — только чтобы сказать сразу, без похода в сеть.
const WEAK_EXTRA = new Set([
  '1212', '1122', '1313', '2121', '2580', '0852', '1004', '2000', '2001',
  '6969', '1010', '4545', '5252', '1112', '7272', '1984', '1990', '2020',
])

export const WEAK_PIN_TEXT = 'Слишком простой PIN — придумай другой (не 1234, 0000 и не повторы).'

export function isWeakPin(pin) {
  const p = String(pin ?? '')
  if (!/^\d{4}$/.test(p)) return false
  if (/^(\d)\1{3}$/.test(p)) return true // 0000, 1111, …
  const d = [...p].map(Number)
  const up = d.every((x, i) => i === 0 || x === (d[i - 1] + 1) % 10)
  const down = d.every((x, i) => i === 0 || x === (d[i - 1] + 9) % 10)
  if (up || down) return true // 1234, 7890, 4321, 0987…
  return WEAK_EXTRA.has(p)
}
