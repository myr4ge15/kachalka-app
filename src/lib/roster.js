// Чистые хелперы кэша ОБЩЕГО ростера учёток (loginDb.users) — без Dexie/сети.
// Потребители: repo.cacheUsers (экран входа) и db/sync/pull.js (pullRoster).
//
// Зачем отдельный модуль: ростер пишут ДВА источника с РАЗНОЙ полнотой выборки —
// экран входа читает login_users анонимно, ДО входа (персональной базы ещё нет), а
// pullRoster тянет полный набор полей. Оба раньше делали clear() + bulkPut, поэтому
// НЕПОЛНАЯ выборка молча обнуляла поля, которых в ней не было: select без `sex` на
// экране входа сбрасывал пол ВСЕМУ ростеру устройства → viewerBoard(undefined) → 'm'
// → все попадали в мужской борд, женский рейтинг исчезал (инцидент 29.07.2026).
// Восстановления не наступало: сигнатура ростера лежала в персональной базе, а
// испорченные данные — в общей, поэтому pull считал, что тянуть нечего.
//
// Поэтому запись — только МЕРЖЕМ, а форму строки фиксирует белый список полей.
// Никаких импортов: модуль обязан оставаться листом графа (как lib/muscles.js).

// Поля, которые вообще имеют право лежать в кэше ростера. Всё лишнее отбрасываем:
// в старой общей базе gym_app в users лежали pin_hash/pin_salt, и после
// migrateLoginZone они могли попасть в loginDb.users. Прежний clear() их вымывал
// первым же pull'ом — при мерже без белого списка они жили бы вечно.
export const ROSTER_FIELDS = ['id', 'name', 'avatar_url', 'sort_order', 'sex']

// Строка ростера в канонической форме. Отсутствующие ключи НЕ добавляем (иначе
// мерж затрёт кэш пачкой undefined — ровно то, от чего этот модуль защищает).
export function pickRosterShape(row) {
  const out = {}
  if (!row) return out
  for (const key of ROSTER_FIELDS) {
    if (key in row) out[key] = row[key]
  }
  return out
}

// План записи ростера: что положить (мержем поверх кэша) и что удалить.
//   - ключ, ПРИСУТСТВУЮЩИЙ во входящей строке, всегда перекрывает кэш — в т.ч.
//     null (снятый аватар, сброшенный пол); сохраняются только ОТСУТСТВУЮЩИЕ;
//   - удаляем только id, которых во входящем списке нет (админ убрал участника);
//   - пустой (но не ошибочный) список ростер НЕ затирает и ничего не удаляет: тот
//     же принцип, что в fetchLeaderboard — единичный сбой прав/RLS иначе оставил бы
//     устройство без пикера входа, т.е. без возможности войти офлайн.
export function planRosterWrite(existing, incoming) {
  const rows = (incoming ?? []).filter((u) => u?.id).map(pickRosterShape)
  if (rows.length === 0) return { puts: [], deleteIds: [] }
  const cache = new Map((existing ?? []).filter((u) => u?.id).map((u) => [u.id, pickRosterShape(u)]))
  const keep = new Set(rows.map((u) => u.id))
  return {
    puts: rows.map((u) => ({ ...cache.get(u.id), ...u })),
    deleteIds: (existing ?? []).map((u) => u?.id).filter((id) => id && !keep.has(id)),
  }
}
