// ============================================================================
// Каталог пользовательских упражнений: чьё что и кому можно править.
//
// Справочник упражнений ОДИН на весь круг (одна таблица `exercises`), поэтому
// «моё» — не отдельный список, а срез общего по `owner_id`. До v5.14.0 колонки
// владельца не существовало вовсе: экран назывался «Мои упражнения», а показывал
// всё, что кто-либо когда-либо добавил, — у двух разных людей списки совпадали
// до строки. Здесь чистая логика этого среза; данные даёт repo.getCustomExercises,
// серверная часть — supabase/exercise-owner.sql.
//
// `owner_id == null` — «ничьё»: легаси-строки, для которых владельца не удалось
// восстановить бэкфиллом. Их показываем в общем разделе и разрешаем править
// кому угодно (отбирать у людей уже заведённые упражнения нельзя).
// ============================================================================

// Можно ли этому человеку править это упражнение.
// Своё (owner_id === userId) или ничьё (owner_id пуст) — да, чужое — нет.
// Зеркалит серверную политику exercises_update.
export function canEditExercise(ex, userId) {
  if (!ex) return false
  const owner = ex.owner_id ?? null
  return owner === null || owner === userId
}

// Разрезать плоский список кастомных упражнений на «добавил я» и «добавили
// другие». Порядок внутри разделов сохраняется тем, каким пришёл список (repo
// уже отсортировал по группе и имени) — здесь только фильтр, без пересортировки.
//
// Ничьи (owner_id пуст) уходят в `others`: обещать «это добавил ты» без данных
// мы больше не хотим — именно эта подмена и была багом. При этом править их
// по-прежнему можно (canEditExercise), так что раздел не декоративный.
export function splitCatalog(list, userId) {
  const all = Array.isArray(list) ? list : []
  const mine = []
  const others = []
  for (const ex of all) {
    if (userId && (ex?.owner_id ?? null) === userId) mine.push(ex)
    else others.push(ex)
  }
  return { mine, others }
}
