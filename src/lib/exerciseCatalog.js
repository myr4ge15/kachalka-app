// Каталог пользовательских упражнений: чье что и кому можно править.
//
// Справочник упражнений ОДИН на весь круг (одна таблица `exercises`), поэтому
// «мое» — не отдельный список, а срез общего по `owner_id`. До v5.14.0 колонки
// владельца не существовало вовсе: экран назывался «Мои упражнения», а показывал
// все, что кто-либо когда-либо добавил, — у двух разных людей списки совпадали
// до строки. Здесь чистая логика раскладки; данные дает repo.getExercises (тот же
// справочник, что у пикера), серверная часть — supabase/exercise-owner.sql.
//
// Состояний ровно ДВА, третьего («кастомное без владельца») быть не должно:
//   is_custom = false           — глобальное упражнение, владельца нет по
//                                 определению, правит только админ;
//   is_custom = true + owner_id — чье-то, правит владелец.
// Промежуточное «кастомное, но ничье» существовало до v5.14.0 и было именно тем
// состоянием, из-за которого экран врал: по флагу «добавил участник», по факту
// ничье, править может кто угодно. Бэкфилл развел этот остаток по двум честным
// состояниям (`exercise-owner.sql`, блоки 2/2b/2c).
// ============================================================================

// Можно ли этому человеку править это упражнение.
// Только свое кастомное. Глобальные (is_custom = false) правит админ через
// admin_update_exercise. Зеркалит серверную политику exercises_update.
export function canEditExercise(ex, userId) {
  if (!ex || !ex.is_custom) return false
  return Boolean(userId) && (ex.owner_id ?? null) === userId
}

// Разрезать справочник на три раздела каталога: «добавил я», «добавили другие»,
// «общие» (глобальные, is_custom = false). Порядок внутри разделов сохраняется
// тем, каким пришел список (repo уже отсортировал по группе и имени) — здесь
// только раскладка, без пересортировки.
//
// Кастомная строка без владельца теоретически возможна только в окно раскатки
// (SQL уже применен, клиент еще старый) — кладем ее к «общим»: обещать «это
// добавил ты» без данных мы больше не хотим, именно эта подмена и была багом.
export function splitCatalog(list, userId) {
  const all = Array.isArray(list) ? list : []
  const mine = []
  const others = []
  const global = []
  for (const ex of all) {
    const owner = ex?.owner_id ?? null
    if (!ex?.is_custom || owner === null) global.push(ex)
    else if (userId && owner === userId) mine.push(ex)
    else others.push(ex)
  }
  return { mine, others, global }
}

// Типы упражнения — для формы и подписи строки каталога (общие для участника и Админки, 23.10.2026).
export const METRIC_OPTIONS = [
  { id: 'weight', label: 'Вес и повторения' },
  { id: 'reps', label: 'Только повторения' },
  { id: 'time', label: 'На время' },
  { id: 'distance', label: 'Дистанция и время' },
]
export const METRIC_LABEL = Object.fromEntries(METRIC_OPTIONS.map((m) => [m.id, m.label.toLowerCase()]))

// Группы мышц для формы: основные из ТЗ + все, что реально встретилось в справочнике (без пустых и
// повторов, порядок — основные, затем найденные).
export const BASE_GROUPS = ['грудь', 'спина', 'ноги', 'плечи', 'бицепс', 'трицепс', 'пресс', 'кардио']
export function catalogGroups(list) {
  const set = new Set(BASE_GROUPS)
  for (const e of Array.isArray(list) ? list : []) {
    const g = String(e?.muscle_group ?? '').trim()
    if (g) set.add(g)
  }
  return Array.from(set)
}
