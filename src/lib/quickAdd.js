// ============================================================================
// Быстрая запись тренировки («в один тап»).
//
// Раньше путь к новой тренировке был трёхшаговым: вкладка «Тренировки» → список →
// «+ Добавить тренировку». Теперь есть плавающая кнопка «+» (FAB) поверх контента
// и прямой интент с Главной — оба ведут сразу в композер (history + selected='new').
//
// Здесь — только ЧИСТАЯ логика видимости FAB (без React/DOM), чтобы правило
// «где кнопка есть, а где мешает» было одним местом и покрывалось тестами.
// ============================================================================

// Вкладки, на которых FAB уместен, — только те, где «записать тренировку» и есть
// главное действие экрана: Главная (стартовая точка дня) и хаб «Тренировки» (на
// мобиле кнопка вверху списка ему уступила место, см. HistoryScreen).
// «Лента» и «Прогресс» — экраны ЧТЕНИЯ: там главное действие другое (реакции /
// выбор упражнения и периода), а круглая кнопка просто перекрывала бы угол
// карточки и графика. На вложенных роутах (профиль, уведомления, админка,
// свежесть, мои упражнения, достижения) — по той же причине.
export const FAB_TABS = ['home', 'history']

/**
 * Показывать ли плавающую кнопку «+».
 *
 * @param {object} p
 * @param {string} p.tab       активная вкладка App
 * @param {boolean} p.busy     хаб «Тренировки» занят собственным под-видом:
 *                             открыт композер/деталь/шаблоны или включён режим
 *                             выбора для экспорта. В обоих случаях FAB либо
 *                             бессмысленен (мы уже в редакторе), либо физически
 *                             налезает на нижнюю панель («Сохранить», бар экспорта).
 * @returns {boolean}
 */
export function canShowFab({ tab, busy = false } = {}) {
  if (busy) return false
  return FAB_TABS.includes(tab)
}
