// ============================================================================
// Быстрая запись тренировки («в один тап»).
//
// Раньше путь к новой тренировке был трёхшаговым: вкладка «Тренировки» → список →
// «+ Добавить тренировку». Теперь есть кнопка «+» по центру нижнего меню и прямой
// интент с Главной — оба ведут сразу в композер (history + selected='new').
//
// Здесь — только ЧИСТАЯ логика состояния кнопки (без React/DOM), чтобы правило
// «где кнопка активна, а где утоплена» было одним местом и покрывалось тестами.
// ============================================================================

/**
 * Состояние кнопки «+» в нижнем меню (v6.0.4).
 *
 * До v6 это была плавающая кнопка поверх контента, и там, где она мешала (экраны
 * чтения, вложенные роуты), её прятали. С v6 «+» живёт ВНУТРИ меню и ничего не
 * перекрывает, а пустое место по центру меню выглядело дырой — поэтому кнопка есть
 * ВСЕГДА, включая вложенные роуты (профиль, уведомления, админка…).
 *
 * Единственный случай — хаб «Тренировки» занят своим под-видом (открыт композер /
 * деталь / итог или режим выбора для экспорта): новая запись там бессмысленна, а
 * приподнятый круг налезал бы на липкую панель («Сохранить», бар экспорта). Тогда
 * круг не пропадает, а «утапливается» в меню — плоский, приглушённый, неактивный.
 *
 * @param {object} [p]
 * @param {boolean} [p.busy]  хаб «Тренировки» занят собственным под-видом
 * @returns {'on'|'sunk'}
 */
export function fabState({ busy = false } = {}) {
  return busy ? 'sunk' : 'on'
}
