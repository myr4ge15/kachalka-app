// Фаза крутилок (v6.3.6): синк в шапке и «обновить» в Ленте крутятся с одной
// скоростью (--spin-dur в index.css), но стартуют в разные моменты — стрелки
// все равно шли вразнобой. Отрицательная задержка = текущее время документа
// ставит любую крутилку в ту фазу, в которой она была бы, начав крутиться при
// загрузке страницы, — поэтому все совпадают при любой длительности оборота
// (в т.ч. замедленной под prefers-reduced-motion).
export function spinPhaseStyle(now = globalThis.performance?.now?.() ?? 0) {
  return { '--spin-phase': `-${Math.max(0, Math.round(now))}ms` }
}
