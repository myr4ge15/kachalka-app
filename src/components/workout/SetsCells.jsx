import { fmtSetList } from '../../lib/metric.js'

// Подходы упражнения для списков (Лента, История, календарь, профиль друга,
// Прогресс, панель автопрогрессии) — одной строкой fmtSetList. «Свой вес» с доп.
// весом/помощью — тоже строкой, со знаком: '+15×12, −17.5×10'. Колонки «повторы
// над весом» (v7.2.3) ломали ровную таблицу карточек и убраны в v7.5.2.
// Презентационный, без состояния.
export default function SetsCells({ metric, sets, sep, empty = '—' }) {
  return fmtSetList(metric, sets, sep) || empty
}
